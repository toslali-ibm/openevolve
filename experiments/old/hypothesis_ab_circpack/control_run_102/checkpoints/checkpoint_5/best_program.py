"""Constructor-based circle packing for n=26 circles"""
import numpy as np


def construct_packing():
    """
    Construct a specific arrangement of 26 circles in a unit square
    that attempts to maximize the sum of their radii.

    Returns:
        Tuple of (centers, radii, sum_of_radii)
        centers: np.array of shape (26, 2) with (x, y) coordinates
        radii: np.array of shape (26) with radius of each circle
        sum_of_radii: Sum of all radii
    """
    # Initialize arrays for 26 circles
    n = 26
    centers = np.zeros((n, 2))

    # Place 26 circles in a staggered grid (approx 5x5 + 1)
    idx = 0
    for r in range(5):
        for c in range(5):
            if idx < n:
                # Staggered hexagonal-like grid
                shift = 0.05 if r % 2 == 0 else -0.05
                centers[idx] = [0.1 + c * 0.2 + shift, 0.1 + r * 0.19]
                idx += 1
    
    # Place the 26th circle in a specific empty spot
    if idx < n:
        centers[idx] = [0.5, 0.9]

    # Simple iterative relaxation to improve spacing
    for _ in range(50):
        for i in range(n):
            for j in range(i + 1, n):
                diff = centers[i] - centers[j]
                dist = np.linalg.norm(diff)
                if dist < 0.18: # Target diameter
                    push = (0.18 - dist) * 0.5 * (diff / (dist + 1e-6))
                    centers[i] += push
                    centers[j] -= push
        centers = np.clip(centers, 0.09, 0.91)

    # Compute maximum valid radii for this configuration
    radii = compute_max_radii(centers)

    # Calculate the sum of radii
    sum_radii = np.sum(radii)

    return centers, radii, sum_radii


def compute_max_radii(centers):
    """
    Compute the maximum possible radii for each circle position
    such that they don't overlap and stay within the unit square.

    Args:
        centers: np.array of shape (n, 2) with (x, y) coordinates

    Returns:
        np.array of shape (n) with radius of each circle
    """
    n = centers.shape[0]
    radii = np.ones(n)

    # First, limit by distance to square borders
    for i in range(n):
        x, y = centers[i]
        # Distance to borders
        radii[i] = min(x, y, 1 - x, 1 - y)

    # Limit by distance to other circles using a fair shrinkage
    # Iterating multiple times ensures a more stable distribution
    for _ in range(10):
        for i in range(n):
            for j in range(i + 1, n):
                dist = np.linalg.norm(centers[i] - centers[j])
                if radii[i] + radii[j] > dist:
                    # Adjust the larger radius more to equalize sizes
                    ratio = radii[i] / (radii[i] + radii[j])
                    radii[i] = dist * ratio
                    radii[j] = dist * (1 - ratio)

    return radii


